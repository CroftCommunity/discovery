// RUN_REPORT.md generator.
//
// The report is a deliverable (Part 5): it carries the E5 measured-vs-predicted
// table, per-period statement summaries, and the plain-language sentence from
// each experiment in order, so the report itself reads as the Part 4 narrative.

import { writeFileSync } from "node:fs";
import type { ExperimentResult } from "./experiment.ts";

const NARRATIVE_INTRO = `A customer, Ada, brings her items to the co-op. First the two parties become keys to
each other (E0). Ada's items get names no one can forge (E1) and she signs the list of what she is
owed (E2). Bytes move and both sides sign every receipt (E3), months close into a chain of agreed
statements (E4), and Ada picks how suspicious she feels like being, at cost (E5, E6). Years later she
seals the collection for her family (E7), and eventually chooses the tombstone (E8). Along the way the
co-op waives a fee once, because it could afford to and the books say so out loud (E9). The last
experiment (E10) is the door left open for a stronger guarantee, deliberately not walked through yet.`;

export function writeReport(
  path: string,
  results: ExperimentResult[],
  meta: { seed: number; generatedNote: string },
): void {
  const lines: string[] = [];
  lines.push("# RUN_REPORT — Item Storage Protocol");
  lines.push("");
  lines.push(`status: generated by \`npm run\` / \`node scripts/run.ts\` (deterministic; seed base ${meta.seed})`);
  lines.push("");
  lines.push(meta.generatedNote);
  lines.push("");
  lines.push("## The narrative");
  lines.push("");
  lines.push(NARRATIVE_INTRO);
  lines.push("");
  lines.push("## What each experiment proved (in order)");
  lines.push("");
  for (const r of results) {
    lines.push(`- **${r.id} — ${r.title}:** ${r.sentence}`);
  }
  lines.push("");
  lines.push("---");
  lines.push("");
  for (const r of results) {
    lines.push(`## ${r.id}. ${r.title}`);
    lines.push("");
    lines.push(`> ${r.sentence}`);
    lines.push("");
    lines.push(r.reportMd);
    lines.push("");
  }
  lines.push("---");
  lines.push("");
  lines.push(
    "Every mock standing in for a real mechanism (hex hashes for CIDs, in-process actors for the",
  );
  lines.push(
    "network, deleted capabilities for destroyed keys, deterministic JSON for DAG-CBOR) is marked",
  );
  lines.push("in the source with a comment beginning `SEAM:` — grep them to enumerate the production gaps.");
  lines.push("");
  writeFileSync(path, lines.join("\n"));
}

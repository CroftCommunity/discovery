// The underwriting packet as a build artifact (E13).
//
// DILIGENCE_REPORT.md is generated ENTIRELY by the funder side — this module
// imports only its own verifier and Node built-ins, never the actors' code — so
// the co-op cannot influence the report's contents except by changing the
// underlying signed facts. "The loan application is a build artifact."

import { writeFileSync } from "node:fs";
import type { CovenantReport, FunderResult, LedgerClass } from "./verifier.ts";

const dollars = (cents: number): string =>
  (cents < 0 ? "-" : "") + "$" + Math.round(Math.abs(cents) / 100).toLocaleString("en-US");

export interface DiligenceInputs {
  coopName: string;
  periods: number;
  funder: FunderResult;
  covenants: CovenantReport;
  ledgers: LedgerClass[];
  generatedNote: string;
}

export function writeDiligenceReport(path: string, d: DiligenceInputs): string {
  const L: string[] = [];
  L.push(`# DILIGENCE_REPORT — ${d.coopName}`);
  L.push("");
  L.push("status: generated by the funder-side verifier alone (`funder/`), from the published ledger");
  L.push("files, public keys, audit transcripts, and the public randomness seed — no private access.");
  L.push("");
  L.push(d.generatedNote);
  L.push("");

  // Headline
  const verdict = d.funder.overallOk && d.covenants.ok ? "PASS" : "FAIL";
  L.push(`## Underwriting verdict: **${verdict}**`);
  L.push("");
  L.push(
    `File-only checks ${d.funder.overallOk ? "passed" : "FAILED"}; covenants ${d.covenants.ok ? "passed" : "FAILED"}. ` +
      `Reviewed ${d.periods} periods.`,
  );
  L.push("");

  // Co-attested revenue
  L.push("## Co-attested revenue");
  L.push("");
  L.push(
    `Reported revenue ${dollars(d.funder.revenue.reportedCents)}; independently co-attested ` +
      `${dollars(d.funder.revenue.coAttestedCents)} (every entry carries a valid customer countersignature). ` +
      `Match: ${d.funder.revenue.ok ? "✓" : "✗"}.`,
  );
  L.push("");

  // Service delivery
  L.push("## Service delivery (public-randomness audits)");
  L.push("");
  L.push(
    `${d.funder.service.transcriptsChecked} audit transcripts; challenges re-derived from the public ` +
      `beacon and re-fingerprinted. Pass rate ${(d.funder.service.passRate * 100).toFixed(0)}%. ` +
      `Verified: ${d.funder.service.ok ? "✓" : "✗"}.`,
  );
  L.push("");

  // Statement chain + grace
  L.push("## Statement chain & grace");
  L.push("");
  L.push(`- Statement chain intact from genesis: ${d.funder.chain.ok ? "✓" : `✗ (breaks at period ${d.funder.chain.brokenAtPeriod})`}`);
  L.push(`- Grace fully on-book (books balance every period): ${d.funder.grace.ok ? "✓" : `✗ (off-book in period(s) ${d.funder.grace.offBookPeriods.join(", ")})`}`);
  L.push(`- Grace on-book total: ${dollars(d.funder.grace.onBookCents)}`);
  L.push("");

  // Royalty position
  L.push("## Royalty ledger position (E11 instrument)");
  L.push("");
  L.push(
    `Cap ${dollars(d.funder.royalty.capCents)}; paid to date ${dollars(d.funder.royalty.paidCents)}; ` +
      `extinguishment year ${d.funder.royalty.extinguishYear ?? "—"}. ` +
      `Matches instrument terms: ${d.funder.royalty.ok ? "✓" : "✗"}.`,
  );
  if (d.funder.royalty.mismatches.length) {
    for (const m of d.funder.royalty.mismatches) L.push(`  - ⚠ ${m}`);
  }
  L.push("");

  // Covenants
  L.push("## Loan covenants");
  L.push("");
  L.push("| Covenant | Status | Derivation | Ledger lines |");
  L.push("| --- | :---: | --- | --- |");
  for (const c of d.covenants.covenants) {
    const refs = c.ledgerRefs.length ? c.ledgerRefs.map((r) => `\`${r}\``).join("; ") : "—";
    L.push(`| ${c.name} | ${c.ok ? "✓ pass" : "✗ FAIL"} | ${c.detail} | ${refs} |`);
  }
  L.push("");

  // Findings (if any)
  if (d.funder.findings.length) {
    L.push("## Anomalies detected");
    L.push("");
    for (const f of d.funder.findings) {
      L.push(`- **${f.code}**${f.period === null ? "" : ` (period ${f.period})`}: ${f.detail} — \`${f.ledgerRef}\``);
    }
    L.push("");
  }

  // E14 side-by-side page
  L.push("## The scope condition: what the verifier can and cannot bless");
  L.push("");
  L.push(
    "The standard is trustworthy only where the unit is countable at the boundary by both sides. " +
      "Co-attested counts are *verified*; a signed entry whose unit has no boundary-observable count " +
      "is *attested-but-unverifiable* — the signatures are valid, but nothing checks the count.",
  );
  L.push("");
  L.push("| Ledger | Entries | Signatures | Count verifiable | Verdict |");
  L.push("| --- | ---: | :---: | :---: | --- |");
  for (const lc of d.ledgers) {
    L.push(
      `| \`${lc.type}\` | ${lc.count} | ${lc.signaturesValid ? "✓" : "✗"} | ${lc.countVerifiable ? "✓" : "✗"} | ${lc.verdict === "verified" ? "**verified**" : "_attested-but-unverifiable_"} |`,
    );
  }
  L.push("");
  for (const lc of d.ledgers) {
    L.push(`- \`${lc.type}\`: ${lc.note}`);
  }
  L.push("");
  L.push(
    "> The signature attests the count, and the count disciplines the signature; without a countable " +
      "unit, it's signed vibes.",
  );
  L.push("");

  writeFileSync(path, L.join("\n"));
  return path;
}
